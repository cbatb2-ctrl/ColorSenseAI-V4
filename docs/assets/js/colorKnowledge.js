// วิเคราะห์ชื่อสีจาก Hue
// ==========================================

function getColorNameFromHue(hue) {

    if (hue < 15 || hue >= 345) {
        return "แดง";
    }

    if (hue < 30) {
        return "ส้มแดง";
    }

    if (hue < 45) {
        return "ส้ม";
    }

    if (hue < 60) {
        return "ส้มเหลือง";
    }

    if (hue < 90) {
        return "เหลือง";
    }

    if (hue < 120) {
        return "เขียวเหลือง";
    }

    if (hue < 150) {
        return "เขียว";
    }

    if (hue < 180) {
        return "เขียวน้ำเงิน";
    }

    if (hue < 240) {
        return "น้ำเงิน";
    }

    if (hue < 270) {
        return "ม่วงน้ำเงิน";
    }

    if (hue < 300) {
        return "ม่วง";
    }

    if (hue < 345) {
        return "ม่วงแดง";
    }

    return "แดง";
}